#include <bits/stdc++.h>
using namespace std;

// 학생 수와 보석 개수가 최대 10억(10^9)이므로, 합산 시 int 범위(약 21억)를 넘기 때문에 long long 사용
typedef long long ll;

ll n, m; // n: 아이들의 수(N), m: 보석 색상의 수(M)
ll a[300004]; // 각 색상별 보석 개수를 저장하는 배열
ll ret = 1e18; // 답: 질투심의 최솟값 (최솟값을 갱신하기 위해 매우 큰 수 10^18로 초기화)

/**
 * @brief 한 아이가 최대 mid개의 보석을 가질 때, N명의 아이들에게 모든 보석을 나눠줄 수 있는지 판별
 * @param mid 가정한 최대 질투심 (한 아이가 받을 수 있는 최대 보석 개수)
 * @return N명 이하의 아이로 모든 보석을 분배할 수 있으면 true, 아이가 더 필요하면 false
 */
bool check(ll mid) {
    ll num = 0; // 모든 보석을 나누어 주기 위해 필요한 최소 학생 수

    // M가지 색상을 하나씩 확인하며 필요한 학생 수 누적
    for (int i = 0; i < m; i++) {
        // 1. i번 색상 보석을 mid개씩 꽉 채워 받을 수 있는 학생 수
        num += a[i] / mid;

        // 2. 나누어 떨어지지 않고 자투리 보석이 남았다면, 그 나머지를 가져갈 학생 1명이 추가로 필요함 (올림 처리)
        if (a[i] % mid) num++;
    }

    // 필요한 최소 학생 수(num)가 실제 학생 수(n) 이하라면 분배 가능!
    // (남는 n - num명의 학생은 보석을 0개 받으면 되므로 문제 조건에 위배되지 않음)
    return n >= num;
}

int main() {
    // 입출력 속도 향상
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    // 1. 아이들의 수(n)와 색상의 수(m) 입력
    cin >> n >> m;

    // 이분 탐색의 시작 범위 설정
    // lo: 한 아이가 받을 수 있는 최소 보석 수 (0으로 나누는 에러를 막기 위해 1부터 시작)
    // hi: 한 아이가 받을 수 있는 최대 보석 수 (가장 개수가 많은 색상의 보석 수로 설정)
    ll lo = 1, hi = 0, mid;

    // 2. 각 색상별 보석 개수를 입력받으면서 최댓값(hi) 갱신
    for (int i = 0; i < m; i++) {
        cin >> a[i];
        hi = max(hi, a[i]);
    }

    // 3. 이분 탐색(매개 변수 탐색) 수행
    while (lo <= hi) {
        mid = (lo + hi) / 2; // 중간값(질투심 후보) 계산

        // 한 명당 최대 mid개씩 나누어 주는 것이 가능하다면?
        if (check(mid)) {
            ret = min(ret, mid); // 현재 mid 값을 정답 후보로 기록 (최솟값 갱신)
            hi = mid - 1; // 더 작은 질투심으로도 가능한지 왼쪽(작은 값) 범위 탐색
        }
        // 학생 수가 부족해서 mid개씩 나누어 주는 것이 불가능하다면?
        else {
            lo = mid + 1; // 한 명당 더 많이 가져가야 하므로 오른쪽(큰 값) 범위 탐색
        }
    }

    // 4. 질투심의 최솟값 출력
    cout << ret << "\n";
    return 0;
}
