#include <bits/stdc++.h>
using namespace std;

int n, m; // n: 강의의 개수(N), m: 블루레이의 개수(M)
int lo, hi, ret; // lo: 이분 탐색 하한, hi: 이분 탐색 상한, ret: 답(블루레이 최소 크기)
int a[100004]; // 각 강의의 길이를 순서대로 저장하는 배열
int sum; // 모든 강의 길이의 총합 (블루레이가 1개일 때 필요한 최대 크기)
int mx; // 가장 긴 강의 1개의 길이 (블루레이가 가져야 할 최소한의 크기)

/**
 * @brief 블루레이 1개의 크기가 mid일 때, M개 이하의 블루레이에 모든 강의를 녹화할 수 있는지 판별
 * @param mid 가정한 블루레이 1개의 최대 녹화 용량(분)
 * @return M개 이하의 블루레이로 모두 녹화 가능하면 true, 초과하면 false
 */
bool check(int mid) {
    // [필수 조건] 가장 긴 강의 1개조차 담지 못하는 크기라면 절대 녹화 불가능
    if (mx > mid) return false;

    int temp = mid; // 새 블루레이를 꺼낼 때 용량을 초기화하기 위해 원래 크기(mid)를 백업해 둠
    int cnt = 0; // 꽉 차서 마감된 블루레이의 개수

    // 0번 강의부터 n-1번 강의까지 순서대로 블루레이에 녹화
    for (int i = 0; i < n; i++) {
        // 현재 블루레이의 남은 용량(mid)에 i번 강의를 넣을 수 없다면?
        if (mid - a[i] < 0) {
            mid = temp; // 새 블루레이를 꺼내 용량을 원래 크기(temp)로 가득 채움
            cnt++; // 방금 다 쓴 블루레이 1개 카운트 증가
        }
        // 현재 블루레이에 i번 강의를 녹화하고 남은 용량 차감
        mid -= a[i];
    }

    // 반복문이 끝난 뒤, 마지막으로 사용 중이던 블루레이에 강의가 하나라도 들어있다면(남은 용량 != 초기 용량)
    // 그 마지막 블루레이도 개수에 포함시켜야 함
    if (mid != temp) cnt++;

    // 사용한 총 블루레이 개수(cnt)가 목표 개수(m) 이하라면 성공!
    // (만약 m개보다 적게 썼다면, 남은 빈 블루레이를 그대로 두거나 강의를 더 잘게 나누면 m개를 맞출 수 있음)
    return cnt <= m;
}

int main() {
    // 입출력 속도 향상
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    // 1. 강의 수(n)와 블루레이 수(m) 입력
    cin >> n >> m;

    // 2. 각 강의 길이를 입력받으면서 전체 합(sum)과 최댓값(mx) 계산
    for (int i = 0; i < n; i++) {
        cin >> a[i];
        sum += a[i]; // 모든 강의를 1장에 몰아넣을 때의 크기
        mx = max(mx, a[i]); // 단일 강의 중 가장 긴 길이
    }

    // 3. 이분 탐색 범위 설정 (0부터 전체 길이 합 sum까지)
    lo = 0;
    hi = sum;

    // 4. 이분 탐색 수행
    while (lo <= hi) {
        int mid = (lo + hi) / 2; // 중간값(블루레이 크기 후보)

        // mid 크기의 블루레이로 M개 이내 녹화가 가능하다면?
        if (check(mid)) {
            hi = mid - 1; // 더 작은 크기로도 가능한지 왼쪽(작은 값) 범위 탐색
            ret = mid; // 현재 가능한 크기 기록 (탐색이 진행될수록 더 작은 값으로 갱신됨)
        }
        // M개를 초과해서 블루레이가 부족하다면?
        else {
            lo = mid + 1; // 블루레이 크기를 더 늘려야 하므로 오른쪽(큰 값) 범위 탐색
        }
    }

    // 5. 가능한 블루레이 크기의 최솟값 출력
    cout << ret << "\n";
    return 0;
}
